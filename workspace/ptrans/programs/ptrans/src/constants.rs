use anchor_lang::prelude::*;

#[constant]
pub const POOL_SEED: &[u8] = b"pool";

#[constant]
pub const NULLIFIER_SEED: &[u8] = b"nullifier";

#[constant]
pub const VAULT_SEED: &[u8] = b"vault";

/*
* Глубина дерева Меркла - 20 уровней для масштабируемости.
* Каждый уровень удваивает количество возможных листьев.
* Глубина 20 это 2^20 = 1 048 576 депозитов (листьев) для хранения обязательств.
* Это число равно 1 Мегабайту или 1 Мибибайту (МиБ).
*/
pub const TREE_DEPTH: usize = 20;

/*
* Максимальное количество депозитов, которое может вместить наш пул.
* 1 << 20 — это битовый сдвиг, результат которого равен 2^20 = 1 048 576.
* Как только дерево заполнится, новые депозиты принимать будет нельзя.
*/
pub const MAX_LEAVES: u64 = 1 << TREE_DEPTH;

// История корней (кольцевой буфер)
/*
* Мы храним последние 10 корней Меркла в кольцевом буфере.
* Когда кто-то вносит депозит, корень меняется.
*
* Если бы мы хранили только текущий корень,
* то у пользователя, который сгенерировал ZK-доказательство
* для чуть более старого корня,
* вывод средств завершился бы ошибкой.
*
* Сохраняя историю недавних корней,
* мы даем пользователям временное окно
* для отправки транзакции на вывод средств до того,
* как их доказательство станет недействительным.
*/
pub const ROOT_HISTORY_SIZE: usize = 10;

// Минимальная сумма депозита
pub const MIN_DEPOSIT_AMOUNT: u64 = 1_000_000; // 0.001 SOL

// Количество публичных входов для верификатора
// NR = "number of" (количество) — стандартное сокращение в криптографическом коде
pub const NR_PUBLIC_INPUTS: u32 = 4;

/*
* Это корень Меркла для дерева без листьев
* (где все позиции изначально заполнены нулями
* и последовательно захешированы до самого верха).
*
* Правильное значение будет получено из Noir схемы в tests/test_ptrans.rs
*
* Данный 32-байтный массив — это результат хеширования Poseidon2
* для пустого дерева глубиной 20 (выглядит как стандартный 32-байтный хеш).
*/
pub const EMPTY_ROOT: [u8; 32] = [0u8; 32];

